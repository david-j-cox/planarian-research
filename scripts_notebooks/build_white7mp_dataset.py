#!/usr/bin/env python3
"""
build_white7mp_dataset.py

Build a YOLO pose dataset from the hand-labeled white-7MP frames
(realtime_runs/label_white7mp) to fine-tune the S3 worm localizer onto the
go-to rig. Unlike the S3 dataset (pseudo-labels from the classical tracker),
these are 600 human labels: 400 'active' (used here for train/val) and 200
'eval' (HELD OUT -- never written, so the localizer eval stays honest).

Labels carry a box + head only (no tail), so we keep the S3 model's
kpt_shape [2, 3] for clean weight transfer and supervise head (v=2) while
marking tail unlabeled (v=0, ignored by the keypoint loss).

Usage:
  python build_white7mp_dataset.py \
      --label_dir ../realtime_runs/label_white7mp \
      --videos_dir ../live_capture \
      --out ../realtime_runs/yolo_white7mp --val_frac 0.1
"""
import argparse
import json
import os
import numpy as np
import cv2


def parse_args():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--label_dir", default=os.path.join(here, "..", "realtime_runs", "label_white7mp"))
    ap.add_argument("--videos_dir", default=os.path.join(here, "..", "live_capture"))
    ap.add_argument("--out", default=os.path.join(here, "..", "realtime_runs", "yolo_white7mp"))
    ap.add_argument("--val_frac", type=float, default=0.1,
                    help="Fraction of ACTIVE frames held out for train-time val (monitoring only).")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--jpg_quality", type=int, default=92)
    return ap.parse_args()


def main():
    a = parse_args()
    man = {it["id"]: it for it in json.load(open(os.path.join(a.label_dir, "manifest.json")))["items"]}
    lab = {int(k): v for k, v in json.load(open(os.path.join(a.label_dir, "labels.json"))).items()}

    # Train ONLY on active, worm-present frames. Eval frames are never touched.
    train_ids = [k for k in lab if man[k]["pool"] == "active" and lab[k].get("present")]
    print(f"active worm-present frames: {len(train_ids)}  (eval pool held out entirely)")

    rng = np.random.default_rng(a.seed)
    val_ids = set(rng.choice(train_ids, size=int(round(len(train_ids) * a.val_frac)), replace=False).tolist())

    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        os.makedirs(os.path.join(a.out, sub), exist_ok=True)

    # Group by video so each file is opened once; seek to the needed frames.
    by_vid = {}
    for k in train_ids:
        by_vid.setdefault(man[k]["video"], []).append(k)

    counts = {"train": 0, "val": 0}
    skipped = 0
    for vid, ks in sorted(by_vid.items()):
        vpath = os.path.join(a.videos_dir, vid)
        if not os.path.exists(vpath):
            print(f"  WARN missing video, skipping: {vpath}")
            continue
        cap = cv2.VideoCapture(vpath)
        W = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
        H = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
        stem = os.path.splitext(vid)[0]
        for k in ks:
            f = man[k]["frame"]
            cap.set(cv2.CAP_PROP_POS_FRAMES, int(f))
            ok, frame = cap.read()
            if not ok:
                skipped += 1
                continue
            x0, y0, x1, y1 = lab[k]["box"]
            bw, bh = x1 - x0, y1 - y0
            if bw <= 1 or bh <= 1:
                skipped += 1
                continue
            split = "val" if k in val_ids else "train"
            xc = (x0 + x1) / 2.0 / W
            yc = (y0 + y1) / 2.0 / H
            wn, hn = bw / W, bh / H
            # cls xc yc w h  head(x,y,v)  tail(x,y,v=0 -> unlabeled, ignored).
            # head v=2 when marked, else v=0 (some active frames have no head).
            head = lab[k].get("head")
            if head:
                hx, hy = float(head[0]) / W, float(head[1]) / H
                head_str = f"{hx:.6f} {hy:.6f} 2"
            else:
                head_str = "0 0 0"
            label = f"0 {xc:.6f} {yc:.6f} {wn:.6f} {hn:.6f} {head_str} 0 0 0\n"
            base = f"{stem}_f{f:06d}"
            cv2.imwrite(os.path.join(a.out, f"images/{split}", base + ".jpg"),
                        frame, [cv2.IMWRITE_JPEG_QUALITY, a.jpg_quality])
            with open(os.path.join(a.out, f"labels/{split}", base + ".txt"), "w") as fh:
                fh.write(label)
            counts[split] += 1
        cap.release()
        print(f"  {stem}: wrote {len([k for k in ks])} labeled frames")

    yaml_path = os.path.join(a.out, "data.yaml")
    with open(yaml_path, "w") as f:
        f.write(
            "# Auto-generated by build_white7mp_dataset.py\n"
            f"path: {os.path.abspath(a.out)}\n"
            "train: images/train\n"
            "val: images/val\n"
            "kpt_shape: [2, 3]   # head, tail; tail unlabeled (v=0) in white-7MP set\n"
            "flip_idx: [0, 1]\n"
            "names:\n"
            "  0: worm\n"
        )
    print(f"\nDONE  train={counts['train']}  val={counts['val']}  skipped={skipped}")
    print(f"data.yaml -> {yaml_path}")


if __name__ == "__main__":
    main()
